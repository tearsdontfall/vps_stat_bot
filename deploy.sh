#!/bin/bash

# ==============================================================================
# НАСТРОЙКИ СЕРВЕРА И ПРОЕКТА
# ==============================================================================
# PROJECT_DIR — путь к папке бота на удаленном сервере VPS
PROJECT_DIR="/opt/traffic_bot/vps_stat_bot"
CONTAINER_NAME="my_traffic_bot"
IMAGE_NAME="traffic_bot"

echo "🚀 [VPS] Запуск процесса автоматического деплоя бота..."

# 1. Переходим в рабочую директорию на сервере
cd "$PROJECT_DIR" || { echo "❌ Ошибка: Папка $PROJECT_DIR не найдена на сервере!"; exit 1; }

# 2. Скачиваем свежие изменения из репозитория GitHub
echo "📥 [VPS] Получение обновлений из GitHub..."
git pull origin main

# 3. Безопасность: проверяем наличие конфигурационного файла .env
# Напоминание: файл .env должен лежать на сервере постоянно, в git его добавлять нельзя!
if [ ! -f ".env" ]; then
    echo "🚨 КРИТИЧЕСКАЯ ОШИБКА: Файл .env отсутствует в папке $PROJECT_DIR на сервере!"
    echo "Пожалуйста, создайте его на VPS вручную перед запуском бота."
    exit 1
fi

# 4. Автоматически выставляем права на исполнение для скрипта мониторинга системы
echo "⚙️ [VPS] Настройка прав для скрипта сбора метрик (system_stats.sh)..."
chmod +x system_stats.sh

# 5. Останавливаем старый Docker-контейнер, чтобы освободить порты и ресурсы
echo "🗑️ [VPS] Остановка и удаление старого контейнера..."
docker rm -f $CONTAINER_NAME 2>/dev/null

# 6. Собираем новый Docker-образ. Флаг --no-cache гарантирует чтение свежего bot.py
echo "📦 [VPS] Сборка нового Docker-образа без использования кэша..."
docker build --no-cache -t $IMAGE_NAME .

# 7. Запуск контейнера со сквозным сетевым режимом и монтированием двух файлов данных
echo "▶️ [VPS] Запуск обновленного контейнера..."
docker run -d \
  --name $CONTAINER_NAME \
  --network host \
  -v "$PROJECT_DIR/vnstat_data.json:/app/vnstat_data.json" \
  -v "$PROJECT_DIR/system_data.json:/app/system_data.json" \
  --restart unless-stopped \
  $IMAGE_NAME

echo "✅ [VPS] Деплой успешно завершен! Бот запущен."
echo "Проверить статус контейнера можно командой: docker ps"