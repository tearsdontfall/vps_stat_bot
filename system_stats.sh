#!/bin/bash

# ==============================================================================
# НАСТРОЙКА ОКРУЖЕНИЯ ДЛЯ ПЛАНИРОВЩИКА CRON
# ==============================================================================
# Явно указываем пути к системным утилитам, чтобы Cron видел команды grep, awk, bc, tr
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin

# Absolute путь к папке нашего бота на сервере VPS
PROJECT_DIR="/opt/traffic_bot/vps_stat_bot"

# ==============================================================================
# СБОР МЕТРИК ОПЕРАТИВНОЙ ПАМЯТИ (RAM)
# ==============================================================================
# 1. Получаем чистую строку "Mem:...", сжимая множественные пробелы в один
ram_line=$(free -m | grep -i '^mem:' | tr -s ' ')

# 2. Вытаскиваем total (вторая колонка) и used (третья колонка) в мегабайтах
# Кавычки строго закрыты с обеих сторон: '{print $2}'
ram_total_mb=$(echo "$ram_line" | awk '{print $2}')
ram_used_mb=$(echo "$ram_line" | awk '{print $3}')

# Защита: если вдруг данные не считались, ставим 1, чтобы не было деления на ноль
if [ -z "$ram_total_mb" ] || [ "$ram_total_mb" -eq 0 ]; then
    ram_total_mb=1
fi

# 3. Переводим мегабайты в читаемые гигабайты и проценты через калькулятор bc
ram_total_gb=$(echo "scale=2; $ram_total_mb / 1024" | bc)
ram_used_gb=$(echo "scale=2; $ram_used_mb / 1024" | bc)
ram_pct=$(echo "scale=2; ($ram_used_mb * 100) / $ram_total_mb" | bc)

# ==============================================================================
# СБОР МЕТРИК ДИСКА И ПРОЦЕССОРА (CPU)
# ==============================================================================
# Собираем данные по диску в корневой папке '/', убираем буквы G и M, если они есть
disk_total_gb=$(df -h / | awk 'NR==2 {print $2}' | sed 's/G//; s/M//')
disk_free_gb=$(df -h / | awk 'NR==2 {print $4}' | sed 's/G//; s/M//')

# Считываем среднюю нагрузку на процессор за 1 минуту (первое число из loadavg)
cpu_load=$(cat /proc/loadavg | awk '{print $1}')

# ==============================================================================
# ЗАПИСЬ ДАННЫХ В JSON ФАЙЛ
# ==============================================================================
cat <<EOF > "$PROJECT_DIR/system_data.json"
{
  "ram": {
    "total_gb": "${ram_total_gb:-0}",
    "used_gb": "${ram_used_gb:-0}",
    "pct": "${ram_pct:-0}"
  },
  "disk": {
    "total_gb": "${disk_total_gb:-0}",
    "free_gb": "${disk_free_gb:-0}"
  },
  "cpu": {
    "load": "${cpu_load:-0.00}"
  }
}
EOF

# Вывод в консоль для ручной проверки
echo "=== Локальная проверка сбора метрик ==="
echo "Очищенная строка памяти: $ram_line"
echo "RAM Total: $ram_total_gb GB, Used: $ram_used_gb GB ($ram_pct%)"
echo "Disk Total: $disk_total_gb GB, Free: $disk_free_gb GB"
echo "CPU Load: $cpu_load"