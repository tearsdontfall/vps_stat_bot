#!/bin/bash

# ==============================================================================
# НАСТРОЙКА ОКРУЖЕНИЯ ДЛЯ ПЛАНИРОВЩИКА CRON
# ==============================================================================
# Явно указываем системные пути, чтобы Cron видел утилиты free, df, bc и awk
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin

# Абсолютный путь к папке нашего проекта на сервере
PROJECT_DIR="/opt/traffic_bot/vps_stat_bot"

# ==============================================================================
# СБОР СИСТЕМНЫХ МЕТРИК VPS
# ==============================================================================

# 1. Сбор метрик оперативной памяти RAM (в мегабайтах)
# ИСПРАВЛЕНИЕ: Используем универсальный выбор второй строки (NR==2) вместо фильтра '^Mem:'
ram_total_mb=$(free -m | awk 'NR==2 {print $2}')
ram_used_mb=$(free -m | awk 'NR==2 {print $3}')

# Переводим мегабайты в читаемые гигабайты и проценты с помощью утилиты bc
ram_total_gb=$(echo "scale=2; $ram_total_mb / 1024" | bc)
ram_used_gb=$(echo "scale=2; $ram_used_mb / 1024" | bc)
ram_pct=$(echo "scale=2; ($ram_used_mb * 100) / $ram_total_mb" | bc)

# 2. Сбор метрик постоянной памяти Диска (корень системы '/')
disk_total_gb=$(df -h / | awk 'NR==2 {print $2}' | sed 's/G//')
disk_free_gb=$(df -h / | awk 'NR==2 {print $4}' | sed 's/G//')

# 3. Сбор метрик процессора CPU (средняя нагрузка Load Average за 1 минуту)
cpu_load=$(cat /proc/loadavg | awk '{print $1}')

# ==============================================================================
# ЗАПИСЬ ДАННЫХ В СИНХРОНИЗИРОВАННЫЙ JSON
# ==============================================================================
# Перезаписываем файл system_data.json актуальной структурой.
cat <<EOF > "$PROJECT_DIR/system_data.json"
{
  "ram": {
    "total_gb": "${ram_total_gb:-0}",
    "used_gb": "${ram_used_gb:-0}",
    "pct": "${ram_pct:-0}"
  },
  "disk": {
    "total_gb": "${disk_total_gb:-0}",
    "free_gb": "${disk_free_gb:-0}"
  },
  "cpu": {
    "load": "${cpu_load:-0}"
  }
}
EOF